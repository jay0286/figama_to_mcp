class Recipe {
  final int id;
  final String name;
  final String description;
  final String image;
  final String tag;
  final String cookTime;
  final String calories;

  Recipe({
    required this.id,
    required this.name,
    required this.description,
    required this.image,
    required this.tag,
    required this.cookTime,
    required this.calories,
  });
}
